"""Plot throughput ratio curves for selected RayWise models.

This module reads the throughput summary CSV generated by the throughput
pipeline and writes a comparison plot with user-facing model labels.
"""

from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


SRC_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SUMMARY_CSV_PATH = SRC_ROOT / "evaluation" / "throughput" / "outputs" / "throughput_summary.csv"
DEFAULT_OUTPUT_PLOT_PATH = SRC_ROOT / "evaluation" / "throughput" / "outputs" / "throughput_ratio_by_model.png"
MODEL_LABEL_MAP = {
    "joint_1dcnn_top1": "Proposed",
    "ensemble_cnn1d_stacking": "Proposed-Ensemble",
    "distilled_1dcnn_motpe_top1": "Proposed-Distilled (MOTPE)",
}


def load_throughput_summary(
    summary_csv_path: Path,
    model_label_map: dict[str, str],
) -> pd.DataFrame:
    """Load and normalize throughput summary records for plotting.

    Args:
        summary_csv_path (Path): Absolute or relative path to the CSV file that
            contains at least the columns ``model_name``, ``k``, and
            ``throughput_ratio``.
        model_label_map (dict[str, str]): Mapping from raw internal model names
            to human-readable labels used in the plot legend. Rows whose
            ``model_name`` is not present in this mapping are excluded from the
            returned DataFrame so the chart includes only explicitly selected
            models.

    Returns:
        pd.DataFrame: DataFrame with columns ``model_name``, ``model_label``,
        ``k``, and ``throughput_ratio`` sorted by model label and ``k``.

    Raises:
        FileNotFoundError: If ``summary_csv_path`` does not exist.
        ValueError: If required CSV columns are missing or no rows match the
            selected model names.

    Examples:
        >>> df = load_throughput_summary(DEFAULT_SUMMARY_CSV_PATH, MODEL_LABEL_MAP)
        >>> sorted(df["model_label"].unique())
        ['Proposed', 'Proposed-Distilled (MOTPE)', 'Proposed-Ensemble']
    """

    if not summary_csv_path.is_file():
        raise FileNotFoundError(f"Throughput summary CSV not found: {summary_csv_path}.")

    summary_df = pd.read_csv(summary_csv_path)
    required_columns = {"model_name", "k", "throughput_ratio"}
    missing_columns = required_columns.difference(summary_df.columns)
    if missing_columns:
        raise ValueError(
            f"CSV {summary_csv_path} is missing required columns: {sorted(missing_columns)}."
        )

    selected_df = summary_df[summary_df["model_name"].isin(model_label_map.keys())].copy()
    if selected_df.empty:
        raise ValueError(
            "No rows found for the requested model names. "
            f"Expected one of: {sorted(model_label_map.keys())}."
        )

    selected_df["model_label"] = selected_df["model_name"].map(model_label_map)
    selected_df["k"] = pd.to_numeric(selected_df["k"], errors="raise")
    selected_df["throughput_ratio"] = pd.to_numeric(selected_df["throughput_ratio"], errors="raise")
    selected_df = selected_df.sort_values(["model_label", "k"]).reset_index(drop=True)
    return selected_df[["model_name", "model_label", "k", "throughput_ratio"]]


def plot_throughput_ratio_by_model(
    throughput_df: pd.DataFrame,
    output_plot_path: Path,
) -> Path:
    """Create and save a throughput ratio line chart grouped by model.

    Args:
        throughput_df (pd.DataFrame): Table returned by
            :func:`load_throughput_summary` with one row per ``(model, k)``
            point and numeric ``throughput_ratio`` values in ``[0, 1]``.
        output_plot_path (Path): Destination path for the generated PNG figure.
            Parent directories are created automatically when missing.

    Returns:
        Path: The path where the figure was written.

    Raises:
        ValueError: If ``throughput_df`` is empty.

    Examples:
        >>> df = load_throughput_summary(DEFAULT_SUMMARY_CSV_PATH, MODEL_LABEL_MAP)
        >>> output = plot_throughput_ratio_by_model(df, DEFAULT_OUTPUT_PLOT_PATH)
        >>> output.name
        'throughput_ratio_by_model.png'
    """

    if throughput_df.empty:
        raise ValueError("throughput_df is empty and cannot be plotted.")

    output_plot_path.parent.mkdir(parents=True, exist_ok=True)

    figure, axis = plt.subplots(figsize=(9, 5))
    for model_label, model_df in throughput_df.groupby("model_label", sort=False):
        axis.plot(
            model_df["k"],
            model_df["throughput_ratio"],
            marker="o",
            linewidth=2.0,
            markersize=5,
            label=model_label,
        )

    axis.set_title("Throughput Ratio vs Top-k")
    axis.set_xlabel("k")
    axis.set_ylabel("throughput_ratio")
    axis.set_ylim(0.0, 1.02)
    axis.grid(True, linestyle="--", linewidth=0.8, alpha=0.4)
    axis.legend()
    figure.tight_layout()
    figure.savefig(output_plot_path, dpi=200)
    plt.close(figure)
    return output_plot_path


def create_throughput_ratio_plot(
    summary_csv_path: Path = DEFAULT_SUMMARY_CSV_PATH,
    output_plot_path: Path = DEFAULT_OUTPUT_PLOT_PATH,
    model_label_map: dict[str, str] = MODEL_LABEL_MAP,
) -> Path:
    """Build the selected-model throughput ratio chart from CSV data.

    Args:
        summary_csv_path (Path): CSV source path. The file must follow the
            throughput summary schema produced by the evaluation pipeline.
        output_plot_path (Path): PNG destination path for the chart.
        model_label_map (dict[str, str]): Mapping that controls which models are
            included and how each one is named in the chart legend.

    Returns:
        Path: Path to the saved plot image.

    Raises:
        FileNotFoundError: Propagated from :func:`load_throughput_summary` when
            the source CSV cannot be found.
        ValueError: Propagated from helper functions when input data is invalid
            or the selected model subset is empty.

    Examples:
        >>> create_throughput_ratio_plot()
        PosixPath('.../throughput_ratio_by_model.png')
    """

    throughput_df = load_throughput_summary(
        summary_csv_path=summary_csv_path,
        model_label_map=model_label_map,
    )
    return plot_throughput_ratio_by_model(
        throughput_df=throughput_df,
        output_plot_path=output_plot_path,
    )
